/**
 * Pure logic for GPIO Pin Planner & Conflict Detector
 * Validates pin capabilities, detects multiplexing conflicts,
 * and exports configurations to Markdown tables and C #define headers.
 */

import { McuPinInfo, McuPreset } from '../data/mcu-presets';

export type PinFunction = 
  | 'UNUSED'
  | 'GPIO_IN'
  | 'GPIO_OUT'
  | 'ADC'
  | 'PWM'
  | 'UART_TX'
  | 'UART_RX'
  | 'SPI_SCK'
  | 'SPI_MOSI'
  | 'SPI_MISO'
  | 'SPI_CS'
  | 'I2C_SDA'
  | 'I2C_SCL'
  | 'RESET';

export interface PinAssignment {
  pinIdentifier: string; // matches McuPinInfo.pin
  customLabel: string; // e.g. "STATUS_LED"
  assignedFunction: PinFunction;
}

export interface PinConflictIssue {
  pinIdentifier: string;
  severity: 'error' | 'warning';
  message: string;
}

export interface GpioPlanReport {
  assignedCount: number;
  conflicts: PinConflictIssue[];
  cHeaderCode: string;
  markdownTable: string;
  steps: string[];
}

export function evaluateGpioPlan(
  mcu: McuPreset,
  assignments: Record<string, PinAssignment>
): GpioPlanReport {
  const conflicts: PinConflictIssue[] = [];
  const assignedList = Object.values(assignments).filter((a) => a.assignedFunction !== 'UNUSED');
  const steps: string[] = [
    `1. Target MCU: ${mcu.name} (${mcu.architecture}).`,
    `2. Analyzed ${assignedList.length} assigned pin(s) across ${mcu.pins.length} total package pins.`,
  ];

  // Map pins from MCU preset
  const mcuPinMap = new Map<string, McuPinInfo>();
  mcu.pins.forEach((p) => mcuPinMap.set(String(p.pin), p));

  // Check unique custom labels
  const labelMap = new Map<string, string>();

  for (const assign of assignedList) {
    const pinInfo = mcuPinMap.get(assign.pinIdentifier);

    if (!pinInfo) {
      conflicts.push({
        pinIdentifier: assign.pinIdentifier,
        severity: 'error',
        message: `Pin ${assign.pinIdentifier} is not found in ${mcu.name} package.`,
      });
      continue;
    }

    // Check input-only pins
    if (pinInfo.isInputOnly && (assign.assignedFunction === 'GPIO_OUT' || assign.assignedFunction === 'PWM' || assign.assignedFunction === 'UART_TX' || assign.assignedFunction === 'SPI_MOSI' || assign.assignedFunction === 'SPI_SCK')) {
      conflicts.push({
        pinIdentifier: assign.pinIdentifier,
        severity: 'error',
        message: `Pin ${assign.pinIdentifier} is HARDWARE INPUT-ONLY. Cannot assign output function "${assign.assignedFunction}".`,
      });
    }

    // Check if function is supported by this pin
    if (assign.assignedFunction !== 'UNUSED' && assign.assignedFunction !== 'GPIO_IN' && assign.assignedFunction !== 'GPIO_OUT') {
      if (!pinInfo.supportedFunctions.includes(assign.assignedFunction as any)) {
        conflicts.push({
          pinIdentifier: assign.pinIdentifier,
          severity: 'error',
          message: `Pin ${assign.pinIdentifier} (${pinInfo.label}) does not support hardware peripheral "${assign.assignedFunction}". Supported: [${pinInfo.supportedFunctions.join(', ')}].`,
        });
      }
    }

    // Check duplicate custom label
    const cleanLabel = assign.customLabel.trim().toUpperCase();
    if (cleanLabel) {
      if (labelMap.has(cleanLabel)) {
        conflicts.push({
          pinIdentifier: assign.pinIdentifier,
          severity: 'warning',
          message: `Duplicate label "${cleanLabel}" used for both ${labelMap.get(cleanLabel)} and ${assign.pinIdentifier}.`,
        });
      } else {
        labelMap.set(cleanLabel, assign.pinIdentifier);
      }
    }
  }

  // Generate C Header defines
  const cLines: string[] = [
    `/* GPIO Pin Definitions for ${mcu.name} */`,
    `/* Auto-generated by LogicBench GPIO Planner */`,
    `#pragma once`,
    ``,
  ];

  assignedList.forEach((a) => {
    const macroName = a.customLabel.trim() 
      ? a.customLabel.trim().replace(/[^a-zA-Z0-9_]/g, '_').toUpperCase()
      : `PIN_${a.pinIdentifier}`;
    cLines.push(`#define ${macroName}_PIN (${a.pinIdentifier})`);
    cLines.push(`#define ${macroName}_FUNCTION (${a.assignedFunction})`);
  });

  // Generate Markdown Table
  const mdRows: string[] = [
    `### Pinout Configuration Table: ${mcu.name}`,
    ``,
    `| Pin | Hardware Label | Custom Net Name | Assigned Function | Notes |`,
    `| :--- | :--- | :--- | :--- | :--- |`,
  ];

  mcu.pins.forEach((p) => {
    const a = assignments[String(p.pin)];
    const assignedFunc = a ? a.assignedFunction : 'UNUSED';
    const label = a && a.customLabel ? a.customLabel : '-';
    const note = p.notes || (p.isInputOnly ? 'Input-only' : '-');
    mdRows.push(`| **${p.pin}** | ${p.label} | \`${label}\` | **${assignedFunc}** | ${note} |`);
  });

  if (conflicts.length === 0) {
    steps.push(`3. ✓ ALL CONSTRAINTS VALID: No hardware pinout conflicts detected.`);
  } else {
    steps.push(`3. ⚠️ CONFLICTS DETECTED: Found ${conflicts.length} pinout violation(s).`);
  }

  return {
    assignedCount: assignedList.length,
    conflicts,
    cHeaderCode: cLines.join('\n'),
    markdownTable: mdRows.join('\n'),
    steps,
  };
}

/**
 * Self-check assertions to verify GPIO planner conflict checks
 */
export function runGpioPlannerSelfChecks(): boolean {
  try {
    const esp32 = {
      id: 'esp32',
      name: 'ESP32',
      manufacturer: 'Espressif',
      architecture: 'Xtensa',
      defaultClockHz: 80000000,
      allowedClockPresets: [80000000],
      datasheetNotice: 'Notice',
      timers: [],
      pins: [
        { pin: 'GPIO34', label: 'GPIO34', supportedFunctions: ['GPIO_IN', 'ADC'] as any, isInputOnly: true },
        { pin: 'GPIO2', label: 'GPIO2', supportedFunctions: ['GPIO_IN', 'GPIO_OUT', 'PWM'] as any },
      ],
    };

    // Test 1: Assigning GPIO_OUT to GPIO34 (input-only pin) must trigger error
    const report1 = evaluateGpioPlan(esp32, {
      'GPIO34': { pinIdentifier: 'GPIO34', customLabel: 'LED', assignedFunction: 'GPIO_OUT' },
    });
    console.assert(report1.conflicts.length > 0, 'Self-check failed: GPIO34 output assignment must trigger error');

    // Test 2: Valid assignment on GPIO2
    const report2 = evaluateGpioPlan(esp32, {
      'GPIO2': { pinIdentifier: 'GPIO2', customLabel: 'STATUS_LED', assignedFunction: 'GPIO_OUT' },
    });
    console.assert(report2.conflicts.length === 0, 'Self-check failed: GPIO2 output should be valid');

    return true;
  } catch (err) {
    console.error('GPIO Planner self-check error:', err);
    return false;
  }
}

runGpioPlannerSelfChecks();
